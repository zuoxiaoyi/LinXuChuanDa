const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')
const { join } = require('node:path')
const test = require('node:test')

const root = join(__dirname, '..', '..')
const detailJs = readFileSync(join(root, 'pages/detail/detail.js'), 'utf8')
const detailWxml = readFileSync(join(root, 'pages/detail/detail.wxml'), 'utf8')
const detailWxss = readFileSync(join(root, 'pages/detail/detail.wxss'), 'utf8')
const getOutfits = readFileSync(join(root, 'cloudfunctions/getOutfits/index.js'), 'utf8')

test('详情页按日期颜色和天气读取每日推荐', () => {
  assert.match(detailJs, /calendarRecommendations\.publicRange/)
  assert.match(detailJs, /mode:\s*'dailyRecommendation'/)
  assert.match(detailJs, /primaryColors/)
  assert.match(detailJs, /secondaryColors/)
  assert.match(detailJs, /weatherSnapshot/)
})

test('详情页展示左侧色系列表且不再覆盖图片右上角色标', () => {
  assert.match(detailJs, /COLOR_BADGE_MAP/)
  assert.match(detailJs, /DEFAULT_SCENES/)
  assert.match(detailJs, /toSceneColumns/)
  assert.doesNotMatch(detailJs, /colorBadge/)
  assert.doesNotMatch(detailWxml, /outfit-color-dot/)
  assert.match(detailWxml, /bestColumns/)
  assert.match(detailWxml, /secondColumns/)
  assert.match(detailWxml, /未创建/)
  assert.match(detailWxml, /color-chip-dot/)
  assert.match(detailWxml, /rank-description-line/)
  assert.match(detailWxss, /\.color-chip-row\s*\{[^}]*flex-direction:\s*column/s)
  assert.match(detailWxss, /\.color-chip\s*\{[^}]*justify-content:\s*center/s)
  assert.match(detailWxss, /\.rank-description\s*\{[^}]*flex-direction:\s*column/s)
  assert.doesNotMatch(detailWxss, /\.outfit-color-dot/)
  assert.doesNotMatch(detailWxml, /paper-bg/)
})

test('详情页穿搭图使用微信原生大图预览', () => {
  assert.match(detailJs, /onPreviewImage\(e\)/)
  assert.match(detailJs, /wx\.previewImage/)
  assert.match(detailWxml, /bindtap="onPreviewImage"/)
  assert.match(detailWxml, /data-url="\{\{item\.item\.coverUrl\}\}"/)
  assert.doesNotMatch(detailJs, /previewImageUrl/)
  assert.doesNotMatch(detailJs, /onClosePreview/)
  assert.doesNotMatch(detailWxml, /preview-mask/)
  assert.doesNotMatch(detailWxml, /preview-close/)
  assert.doesNotMatch(detailWxss, /\.preview-mask/)
  assert.doesNotMatch(detailWxss, /\.preview-close/)
})

test('getOutfits 云函数提供每日推荐模式', () => {
  assert.match(getOutfits, /dailyRecommendation/)
  assert.match(getOutfits, /bestList/)
  assert.match(getOutfits, /secondList/)
  assert.match(getOutfits, /accessories/)
  assert.match(getOutfits, /status:\s*'published'/)
})
